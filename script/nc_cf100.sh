#!/bin/bash

#SBATCH --job-name=lt
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=2
#SBATCH --mem=80GB
#SBATCH --time=48:00:00
#SBATCH --gres=gpu
#SBATCH --partition=a100_1,a100_2,v100,rtx8000

# job info

CORASE=$1
LOSS=$2



# Singularity path
ext3_path=/scratch/$USER/overlay-25GB-500K.ext3
sif_path=/scratch/$USER/cuda11.4.2-cudnn8.2.4-devel-ubuntu20.04.3.sif

# start running
singularity exec --nv \
--overlay ${ext3_path}:ro \
${sif_path} /bin/bash -c "
source /ext3/env.sh
python /scratch/hy2611/GLMC/main_nc.py --dataset cifar100 --loss ${LOSS} \
 --epochs 200 --coarse ${CORASE} --aug pc \
--eps 0.05 --batch_size 64 --store_name coarse_${CORASE}_${LOSS} \
"
